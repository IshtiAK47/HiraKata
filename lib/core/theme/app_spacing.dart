/// Spacing constants for consistent layout throughout the app.
///
/// Uses a 4px base unit with a harmonious scale.
class AppSpacing {
  AppSpacing._();

  /// 4px — Minimal spacing for tight layouts
  static const double xs = 4.0;

  /// 8px — Small spacing for related elements
  static const double sm = 8.0;

  /// 12px — Between small and medium
  static const double md = 12.0;

  /// 16px — Standard spacing
  static const double lg = 16.0;

  /// 24px — Generous spacing for section separation
  static const double xl = 24.0;

  /// 32px — Large spacing for major sections
  static const double xxl = 32.0;

  /// 48px — Extra large spacing for hero areas
  static const double xxxl = 48.0;

  /// 64px — Maximum spacing
  static const double huge = 64.0;

  /// Standard border radius for cards and containers
  static const double radiusSm = 8.0;

  /// Medium border radius
  static const double radiusMd = 12.0;

  /// Large border radius for prominent elements
  static const double radiusLg = 16.0;

  /// Extra large border radius for hero cards
  static const double radiusXl = 24.0;

  /// Full round radius
  static const double radiusFull = 999.0;

  /// Standard page padding
  static const double pagePadding = 20.0;
}
